// Optional browser checks, with mocked AI requests: no API keys or provider charges.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { MODELS } from '../qa-service.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
  await page.route('http://127.0.0.1:4173/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path === '/') return route.fulfill({ contentType: 'text/html', body: html });
    if (path === '/config.js') return route.fulfill({ contentType: 'text/javascript', body: 'window.SAHW_CONFIG={};' });
    if (path === '/api/models') return route.fulfill({ json: { models: [{ ...MODELS[0], available: true }] } });
    return route.fulfill({ json: { status: 'clarification', model: 'Test', sections: [{ text: 'متى تذكرت؟', sourceIds: [] }], sources: [] } });
  });
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto('http://127.0.0.1:4173/?width=' + width);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'guideStart');
    assert.equal(await page.locator('#page-arkan').getAttribute('inert'), '');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'guideStart');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'guideStart');
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'helpFab');
    assert.equal(await page.locator('#guideOverlay').getAttribute('inert'), '');
    await page.locator('[data-rukn="sajda"]').click();
    const first = page.locator('.seg[tabindex="0"]');
    await first.focus();
    assert.equal(await first.getAttribute('data-id'), '4');
    await page.keyboard.press('ArrowLeft');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.id), '9');
    await page.keyboard.press('ArrowRight');
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.id), '4');
    await page.keyboard.press('End');
    await page.keyboard.press('Space');
    assert.ok((await page.locator('#result').getAttribute('class')).includes('batil'));
    assert.equal(await page.locator('#result').getAttribute('aria-hidden'), null);
    await page.locator('[data-clear="remember"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.id), '20');
    assert.equal(await page.locator('#result').getAttribute('aria-hidden'), 'true');
    await page.locator('[data-clear="forget"]').focus();
    await page.keyboard.press('Space');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.id), '4');
    await page.locator('#helpFab').click();
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'helpFab');
    await page.locator('#btnPageOther').click();
    await page.locator('#searchInput').fill('الصلاة');
    await page.waitForFunction(() => !!document.querySelector('.search-count'));
    assert.ok(!/[0-9]/.test(await page.locator('.search-count').innerText()));
    await page.locator('#browseToggle').click();
    assert.ok(!/[0-9]/.test(await page.locator('.topic-count').first().innerText()));
    await page.goBack();
    assert.ok(await page.locator('#page-arkan').isVisible());
    await page.goForward();
    assert.ok(await page.locator('#page-other').isVisible());
    await page.waitForFunction(() => !document.getElementById('qaSend').disabled);
    await page.locator('#qaQuestion').fill('نسيت السجود');
    await page.locator('#qaSend').click();
    await page.waitForFunction(() => document.querySelectorAll('.qa-turn').length === 1);
    assert.ok(await page.locator('.qa-turn').isVisible());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    console.log('PASS keyboard, modal, navigation, Arabic counts and AI panel at width ' + width);
  }
  await page.goto('http://127.0.0.1:4173/?direct=1#other');
  assert.equal(await page.locator('#guideOverlay').getAttribute('inert'), '');
  assert.equal(await page.locator('#page-other').getAttribute('inert'), null);
  await page.locator('#btnPageArkan').click();
  await page.locator('#helpFab').click();
  await page.goBack();
  assert.equal(await page.locator('#guideOverlay').getAttribute('inert'), '');
  assert.equal(await page.locator('#page-other').getAttribute('inert'), null);
  assert.equal(await page.evaluate(() => document.activeElement.id), 'btnPageOther');
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
